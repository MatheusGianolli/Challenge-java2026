-- 7.6 Exceções tratadas (cada bloco mostra a mensagem de erro esperada)
DECLARE
    PROCEDURE testar(p_titulo VARCHAR2, p_sql VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
        DBMS_OUTPUT.PUT_LINE(p_titulo || ': executou sem erro');
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE(p_titulo || ' -> ' || SQLERRM);
    END;
BEGIN
    testar('Veterinário inexistente (-20001)',
        'DECLARE v VARCHAR2(50); BEGIN v := pkg_clyvo.valida_limite_agenda(99999, SYSTIMESTAMP); END;');
    testar('Parâmetro nulo (-20009)',
        'DECLARE v CLOB; BEGIN v := pkg_clyvo.consulta_para_json(NULL); END;');
    testar('Coleção inválida (-20010)',
        'DECLARE v CLOB; BEGIN v := pkg_clyvo.exportar_colecao_json(''PRODUTOS''); END;');
    testar('Período inválido (-20011)',
        'DECLARE c SYS_REFCURSOR; BEGIN pkg_clyvo.resumo_consultas(SYSDATE, SYSDATE - 10, c); END;');
    testar('Data no passado (-20005)',
        'DECLARE v NUMBER; BEGIN pkg_clyvo.agendar_consulta(1, 1, 1, 1, SYSTIMESTAMP - 1, ''Rotina'', NULL, 100, v); END;');
    testar('Valor negativo (-20008)',
        'DECLARE v NUMBER; BEGIN pkg_clyvo.agendar_consulta(1, 1, 1, 1, SYSTIMESTAMP + 5, ''Rotina'', NULL, -10, v); END;');
    ROLLBACK;
END;
/

