            add(v_json, ', "sintomas": '  || j_txt(r.descricao_sintomas));
            add(v_json, ', "diagnostico": '|| j_txt(r.diagnostico));
            add(v_json, ', "veterinario": {"id": ' || j_num(r.vet_id)
