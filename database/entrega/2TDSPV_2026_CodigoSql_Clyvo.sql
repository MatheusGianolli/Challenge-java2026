-- 7.5 Procedure de agendamento + trigger de auditoria (desfeito no final)
DECLARE
    v_pet NUMBER; v_tutor NUMBER; v_clinica NUMBER; v_vet NUMBER; v_id NUMBER;
BEGIN
    pkg_clyvo.definir_usuario_aplicacao('demonstracao_script');
    SELECT id, responsavel_id INTO v_pet, v_tutor FROM tb_pets WHERE microchip = '985112000000101';
    SELECT MIN(id) INTO v_clinica FROM tb_clinicas;
    SELECT MIN(id) INTO v_vet FROM tb_veterinarios;

    pkg_clyvo.agendar_consulta(v_tutor, v_pet, v_clinica, v_vet,
        TRUNC(SYSTIMESTAMP) + 3 + INTERVAL '10' HOUR, 'Rotina', 'Demonstração', 150, v_id);
    DBMS_OUTPUT.PUT_LINE('Consulta agendada: ' || v_id);

    FOR a IN (SELECT tipo_operacao, nome_usuario, usuario_aplicacao
                FROM tb_auditoria_consultas WHERE consulta_id = v_id) LOOP
        DBMS_OUTPUT.PUT_LINE('Auditoria: ' || a.tipo_operacao || ' por ' || a.nome_usuario || ' / ' || a.usuario_aplicacao);
    END LOOP;
    ROLLBACK;
END;
