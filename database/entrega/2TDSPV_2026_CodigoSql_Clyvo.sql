-- =====================================================================
-- PARTE 0 - Limpeza
-- =====================================================================
BEGIN
    FOR obj IN (
        SELECT 'TRIGGER' tipo, 'TRG_AUDITORIA_CONSULTAS' nome FROM dual UNION ALL
        SELECT 'PACKAGE', 'PKG_CLYVO' FROM dual UNION ALL
        SELECT 'TABLE', 'TB_AUDITORIA_CONSULTAS' FROM dual UNION ALL
        SELECT 'TABLE', 'TB_CONSULTAS' FROM dual UNION ALL
        SELECT 'TABLE', 'TB_PETS' FROM dual UNION ALL
        SELECT 'TABLE', 'TB_CLINICAS' FROM dual UNION ALL
        SELECT 'TABLE', 'TB_VETERINARIOS' FROM dual UNION ALL
        SELECT 'TABLE', 'TB_TUTORES' FROM dual
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP ' || obj.tipo || ' ' || obj.nome
                || CASE WHEN obj.tipo = 'TABLE' THEN ' CASCADE CONSTRAINTS PURGE' END;
        EXCEPTION
            WHEN OTHERS THEN NULL; -- objeto ainda não existe
        END;
    END LOOP;
END;
/

