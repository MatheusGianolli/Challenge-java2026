        EXIT WHEN v_cursor%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE(
            RPAD(CASE v_tipo WHEN 'TOTAL_GERAL' THEN '(TOTAL GERAL)' ELSE v_vet END, 24)
            || RPAD(CASE v_tipo WHEN 'SUBTOTAL' THEN '(SUBTOTAL)' WHEN 'TOTAL_GERAL' THEN ' ' ELSE v_tipo_c END, 16)
            || LPAD(v_qtd, 5) || LPAD(TO_CHAR(v_total, 'FM999990.00'), 12));
    END LOOP;
    CLOSE v_cursor;
END;
