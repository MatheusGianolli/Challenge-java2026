            SELECT c.id, c.data_prevista, c.retorno_previsto, c.tipo_consulta,
                   c.descricao_sintomas, c.diagnostico, c.status, c.valor,
                   v.id AS vet_id, v.nome AS vet_nome, v.crmv AS vet_crmv,
