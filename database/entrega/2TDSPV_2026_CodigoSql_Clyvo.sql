CREATE TABLE tb_clinicas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150),
    cnpj VARCHAR2(30),
    email VARCHAR2(150),
    telefone VARCHAR2(30),
    logradouro VARCHAR2(200),
    numero_endereco VARCHAR2(20),
    bairro VARCHAR2(100),
    cidade VARCHAR2(100),
    estado VARCHAR2(2),
    cep VARCHAR2(15),
    status VARCHAR2(20),
