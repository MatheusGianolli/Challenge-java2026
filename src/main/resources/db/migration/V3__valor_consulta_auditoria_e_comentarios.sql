-- ---------------------------------------------------------------------
-- 1. Valor da consulta
-- DEFAULT 0 + NOT NULL: registros ja existentes recebem 0 automaticamente
-- ---------------------------------------------------------------------
ALTER TABLE tb_consultas ADD (
    valor NUMBER(10,2) DEFAULT 0 NOT NULL
);

-- ---------------------------------------------------------------------
-- 2. Restricoes de integridade
-- NOVALIDATE: a regra vale para todo dado novo, sem reprovar linhas
-- antigas que possam existir no banco compartilhado da FIAP
-- ---------------------------------------------------------------------
ALTER TABLE tb_consultas ADD CONSTRAINT ck_consultas_valor
    CHECK (valor >= 0) ENABLE NOVALIDATE;

ALTER TABLE tb_consultas ADD CONSTRAINT ck_consultas_status
    CHECK (status IN ('AGENDADA', 'REALIZADA', 'CANCELADA')) ENABLE NOVALIDATE;

ALTER TABLE tb_tutores ADD CONSTRAINT ck_tutores_status
    CHECK (status IN ('ATIVO', 'INATIVO')) ENABLE NOVALIDATE;

ALTER TABLE tb_veterinarios ADD CONSTRAINT ck_veterinarios_status
    CHECK (status IN ('ATIVO', 'INATIVO')) ENABLE NOVALIDATE;

ALTER TABLE tb_clinicas ADD CONSTRAINT ck_clinicas_status
    CHECK (status IN ('ATIVO', 'INATIVO')) ENABLE NOVALIDATE;

ALTER TABLE tb_pets ADD CONSTRAINT ck_pets_sexo
    CHECK (sexo IN ('M', 'F')) ENABLE NOVALIDATE;

-- Indices nas FKs mais consultadas
-- (o indice veterinario + data atende a validacao de limite de agenda)
CREATE INDEX idx_consultas_vet_data ON tb_consultas (veterinario_id, data_prevista);
CREATE INDEX idx_consultas_pet      ON tb_consultas (pet_id);
CREATE INDEX idx_pets_responsavel   ON tb_pets (responsavel_id);

-- ---------------------------------------------------------------------
-- 3. Tabela de auditoria
-- Sem FK para TB_CONSULTAS de proposito: o historico precisa sobreviver
-- mesmo depois que a consulta auditada for excluida.
-- ---------------------------------------------------------------------
CREATE TABLE tb_auditoria_consultas (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id         NUMBER          NOT NULL,
    nome_usuario        VARCHAR2(100)   NOT NULL,
    usuario_aplicacao   VARCHAR2(100),
    tipo_operacao       VARCHAR2(10)    NOT NULL,
    data_hora_operacao  TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    valores_anteriores  VARCHAR2(4000),
    valores_novos       VARCHAR2(4000),
    CONSTRAINT ck_auditoria_operacao
        CHECK (tipo_operacao IN ('INSERT', 'UPDATE', 'DELETE'))
);

CREATE INDEX idx_auditoria_consulta ON tb_auditoria_consultas (consulta_id);

